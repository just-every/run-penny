import assert from 'node:assert/strict'
export async function scorecardFlow({origin,operator,json,send,pageFor,capture,owner,peer,peerCookie,requests}){
 await owner.goto(origin+'/app/prioritisation',{waitUntil:'networkidle'})
 await owner.getByRole('region',{name:'Scorecards',exact:true}).locator('summary').filter({hasText:/^Create scorecard$/}).click()
 const create=owner.getByRole('form',{name:'Create scorecard',exact:true})
 await create.getByLabel('Scorecard name',{exact:true}).fill('Finance scorecard')
 await create.getByLabel('Criterion 1 name',{exact:true}).fill('Customer impact')
 await create.getByLabel('Criterion 1 weight',{exact:true}).fill('2')
 await create.getByRole('button',{name:'Add criterion',exact:true}).click()
 await create.getByLabel('Criterion 2 name',{exact:true}).fill('Confidence')
 await create.getByLabel('Criterion 2 scale',{exact:true}).selectOption('10')
 await create.getByRole('button',{name:'Create scorecard',exact:true}).click()
 await owner.getByRole('link',{name:'Finance scorecard',exact:true}).click()
 const region=owner.getByRole('region',{name:'Finance scorecard',exact:true})
 const row=region.getByRole('list',{name:'Scorecard ranking',exact:true}).locator(':scope > li').filter({hasText:requests[0].title??'Schedule monthly finance exports'})
 await row.locator('summary').click()
 const form=row.getByRole('form')
 await form.getByLabel('Customer impact (1–5, weight 2)',{exact:true}).fill('4')
 await form.getByLabel('Confidence (1–10, weight 1)',{exact:true}).fill('6')
 await form.getByRole('button',{name:'Save your scores',exact:true}).click()
 await row.getByText('Maya Patel · Yours: 73.33%',{exact:true}).waitFor()
 const {cards}=await json('/api/operator/scorecards',undefined,operator),id=cards.find(card=>card.name==='Finance scorecard').id
 await peer.goto(origin+`/app/prioritisation?card=${id}`,{waitUntil:'networkidle'})
 const peerRegion=peer.getByRole('region',{name:'Finance scorecard',exact:true}),peerRow=peerRegion.getByRole('list',{name:'Scorecard ranking',exact:true}).locator(':scope > li').filter({hasText:requests[0].title??'Schedule monthly finance exports'})
 await peerRow.locator('summary').click()
 await peerRow.getByLabel('Customer impact (1–5, weight 2)',{exact:true}).fill('2')
 await peerRow.getByLabel('Confidence (1–10, weight 1)',{exact:true}).fill('3')
 await peerRow.getByRole('button',{name:'Save your scores',exact:true}).click()
 await peerRow.getByText('Weighted result: 55%',{exact:true}).waitFor()
 await capture(peer,'scorecard-two-scorers',peerRegion)
 assert.equal(await peerRegion.locator('summary').filter({hasText:/^Revise criteria$/}).count(),0)
 await owner.reload({waitUntil:'networkidle'})
 await region.locator('summary').filter({hasText:/^Revise criteria$/}).click()
 const edit=region.getByRole('form',{name:'Revise criteria',exact:true})
 await edit.getByLabel('Criterion 1 name',{exact:true}).fill('Revised customer impact')
 await edit.getByRole('button',{name:'Remove criterion 2',exact:true}).click()
 await edit.getByRole('button',{name:'Save new criteria version',exact:true}).click()
 await region.getByText('Criteria version 1 · Earlier inputs',{exact:true}).first().waitFor()
 await region.getByText('Weighted result: Unscored',{exact:true}).first().waitFor()
 assert.equal(await region.getByText('Customer impact: 4 / 5 · weight 2',{exact:true}).count(),1)
 await capture(owner,'scorecard-revised-history',region)
}
