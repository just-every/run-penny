import assert from 'node:assert/strict'
export async function checkRoadmapViews({runtime,origin,operator,json,owner,pageFor,capture,actor,item}){
 const hydrationErrors=[]
 const watch=page=>page.on('console',message=>{if(message.type()==='error'&&/hydrat|Minified React error #4(?:18|23|25)/i.test(message.text()))hydrationErrors.push(message.text().slice(0,300))})
 watch(owner)
 const hierarchy=await json('/api/operator/hierarchy',undefined,operator),feature=hierarchy.features[0],component=hierarchy.components.find(row=>row.id===feature.componentId),product=hierarchy.products.find(row=>row.id===component.productId)
 assert.ok(feature&&component&&product)
 const records=[item,'01J00000000000000000000001','01J00000000000000000000002'],stamp=new Date().toISOString()
 for(const [index,id] of records.entries()){
  if(index)await runtime.db.prepare("INSERT INTO roadmap_items(id,slug,title,summary,status,created_at,updated_at) VALUES(?,?,?,'Customer workflow','exploring',?,?)").bind(id,id,`synthetic-penny-roadmap-${index}`,stamp,stamp).run()
  await json(`/api/operator/roadmap/${id}`,{title:`synthetic-penny-roadmap-${index}`,summary:'Customer workflow',ownerOperatorId:actor,targetWindow:['2026-11','2026-Q4',null][index],deliveryNotes:null,confidence:null,accountImpact:null,decisionId:null,candidateBetId:null,publicTitle:null,publicSummary:null},operator,'PATCH')
  await json(`/api/operator/hierarchy/feature/${feature.id}/link`,{kind:'roadmap',targetId:id,linked:true},operator,'PUT')
 }
 await json(`/api/operator/roadmap/${records[1]}/move`,{status:'in_progress',reason:'Work started',idempotencyKey:crypto.randomUUID()},operator)
 await json('/api/operator/release-planning',{name:'synthetic-penny-release',releaseDate:'2026-12-14',itemIds:[records[2]]},operator,'POST',201)
 const query=new URLSearchParams({product:product.id,component:component.id,owner:actor,sort:'name'})
 await owner.goto(`${origin}/app/roadmap?${query}`)
 assert.equal(await owner.getByRole('combobox',{name:'Product',exact:true}).locator('option:checked').innerText(),product.name,'Product filters show the selected name')
 const ids=async()=>{await owner.locator('[data-roadmap-layout]').waitFor();return (await owner.locator('[id^="roadmap-item-"]').evaluateAll(nodes=>nodes.map(node=>node.id))).sort()}
 const expected=records.map(id=>'roadmap-item-'+id).sort()
 for(const [button,layout] of [['Status board','board'],['Now / Next / Later','horizons'],['Timeline','timeline']]){
  await owner.getByRole('button',{name:button,exact:true}).click()
  await owner.locator(`[data-roadmap-layout="${layout}"]`).waitFor()
  assert.deepEqual(await ids(),expected)
  await capture(owner,`roadmap-${layout}`)
 }
 await owner.getByRole('combobox',{name:'Timeline scale',exact:true}).selectOption('quarter')
 assert.deepEqual(await ids(),expected)
 await owner.getByText('Release plan: synthetic-penny-release · 2026-12-14',{exact:true}).waitFor()
 const panel=owner.getByRole('region',{name:'Saved views',exact:true})
 await panel.getByText('Save filters, sort and columns',{exact:true}).click()
 const form=panel.getByRole('form',{name:'Save view',exact:true})
 await form.getByRole('textbox',{name:'View name',exact:true}).fill('synthetic-penny-roadmap-shared')
 await form.getByRole('combobox',{name:'Visibility',exact:true}).selectOption('shared')
 await form.getByRole('button',{name:'Save new view',exact:true}).click()
 await panel.getByRole('status').filter({hasText:'View saved.'}).waitFor()
 const view=new URL(owner.url()).searchParams.get('view')
 assert.ok(view)
 await owner.reload();await owner.locator('[data-roadmap-layout="timeline"]').waitFor()
 assert.equal(await owner.getByRole('combobox',{name:'Timeline scale',exact:true}).inputValue(),'quarter')
 assert.deepEqual(await ids(),expected)
 // A real second operator reads the saved definition and the same live list.
 const email='synthetic-penny-roadmap-peer@example.test'
 await json('/api/operator/settings/operators',{email},operator,'POST',202)
 const token=new URL(runtime.outbox.findLast(message=>message.email===email).url).searchParams.get('token')
 const confirmed=await fetch(origin+'/auth/confirm',{method:'POST',redirect:'manual',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({token})})
 assert.equal(confirmed.status,303)
 const cookie=confirmed.headers.get('set-cookie').split(';')[0],peer=await pageFor({cookie})
 watch(peer)
 await peer.goto(`${origin}/app/roadmap?view=${view}`);await peer.locator('[data-roadmap-layout="timeline"]').waitFor()
 assert.deepEqual((await peer.locator('[id^="roadmap-item-"]').evaluateAll(nodes=>nodes.map(node=>node.id))).sort(),expected)
 await capture(peer,'roadmap-shared-peer')
 const card=owner.locator('#roadmap-item-'+records[0])
 await card.getByText('Edit, approve or move',{exact:true}).click()
 const move=card.getByRole('form',{name:'Move roadmap item',exact:true})
 await move.getByRole('combobox',{name:'New status',exact:true}).selectOption('in_progress')
 await move.getByRole('textbox',{name:'Reason',exact:true}).fill('synthetic-penny-keyboard-move')
 await move.getByRole('button',{name:'Record move',exact:true}).focus();await owner.keyboard.press('Enter')
 await card.locator(':scope > div').first().getByText('In progress',{exact:true}).waitFor()
 const context=await json(`/api/operator/roadmap/${records[0]}/context`,undefined,operator)
 assert.ok(context.transitions.some(row=>row.to_status==='in_progress'&&row.reason==='synthetic-penny-keyboard-move'))
 assert.deepEqual(await ids(),expected)
 await capture(owner,'roadmap-keyboard-move')
 assert.deepEqual(hydrationErrors,[],'Roadmap layouts hydrate without mismatches')
}
