import assert from 'node:assert/strict'
import {moderationJourney} from './moderation-runtime.mjs'

await moderationJourney('request-decline',async({origin,operator,json,send,person,pageFor,capture})=>{
 async function captureScreens(page,label,region){
  await capture(page,label,region)
  await page.setViewportSize({width:390,height:844})
  try{await capture(page,label,region)}finally{await page.setViewportSize({width:1440,height:900})}
 }
 const identity=await person(['synthetic-penny-1','example.test'].join('@'),'Eli Wong'),requester={Authorization:`Bearer ${identity.token}`}
 const request=await json('/api/public/requests',{title:'Schedule monthly finance exports',description:'Our finance team needs a monthly CSV before its review.',boardSlug:'finance',idempotencyKey:crypto.randomUUID()},requester,'POST',201)
 await json(`/api/operator/moderation/${request.slug}`,{verdict:'approved',title:'Schedule monthly finance exports',description:'Schedule a monthly CSV for finance reviews.',boardSlug:'finance',displayName:'Eli Wong'},operator)
 await send(`/api/public/requests/${request.slug}/vote`,{},requester,'POST',204)
 const comment=await json(`/api/public/requests/${request.slug}/comments`,{body:'We need to keep the existing manual download, too.'},requester,'POST',201)
 await json(`/api/operator/comments/${comment.id}/moderate`,{verdict:'approved',publicAuthorDisplayName:'Finance customer'},operator)
 const owner=await pageFor({cookie:operator.Cookie}),customer=await pageFor({token:identity.token})
 await owner.goto(origin+`/app/moderation?q=Schedule%20monthly`,{waitUntil:'networkidle'})
 const card=owner.locator('article').filter({has:owner.getByRole('heading',{name:'Schedule monthly finance exports',exact:true})}).first()
 await card.getByText('Discussion, status and request controls',{exact:true}).click()
 const status=card.locator('form').filter({has:owner.getByRole('heading',{name:'Publish status update',exact:true})})
 await status.locator('select[name="status"]').selectOption('planned')
 await status.getByRole('button',{name:'Publish status update',exact:true}).click()
 await status.getByText('Current public status: Planned · Direct status',{exact:true}).waitFor()
 await captureScreens(owner,'planned',card)
 await status.locator('select[name="status"]').selectOption('declined')
 const beforeRefusal=await json(`/api/public/requests/${request.slug}`)
 await status.getByRole('button',{name:'Publish status update',exact:true}).click()
 assert.equal(await status.locator('textarea[name="body"]').evaluate(field=>field.validity.valueMissing),true)
 assert.deepEqual(await json(`/api/public/requests/${request.slug}`),beforeRefusal)
 await captureScreens(owner,'reason-required',card)
 await status.locator('textarea[name="body"]').fill('We are keeping the manual export while we improve reporting.')
 await status.getByRole('button',{name:'Publish status update',exact:true}).click()
 await status.getByText('Current public status: Declined · Direct status',{exact:true}).waitFor()
 await captureScreens(owner,'declined',card)
 await customer.goto(origin+`/portal/feedback/${request.slug}`,{waitUntil:'networkidle'})
 await customer.getByText('This request is declined. New votes and comments are closed; existing discussion stays visible.',{exact:true}).waitFor()
 assert.equal(await customer.getByRole('button',{name:'Send comment for review',exact:true}).count(),0)
 await customer.getByText('We need to keep the existing manual download, too.',{exact:true}).waitFor()
 const history=reason=>customer.getByText(reason,{exact:true}).locator('..')
 await history('We are keeping the manual export while we improve reporting.').getByText('Status update · declined',{exact:true}).waitFor()
 await captureScreens(customer,'customer-declined')
 await status.locator('textarea[name="body"]').fill('Scheduled exports remain outside our current reporting plans.')
 const repeated=owner.waitForResponse(response=>response.url().endsWith(`/api/operator/requests/${request.slug}/status-updates`)&&response.request().method()==='POST')
 await status.getByRole('button',{name:'Publish status update',exact:true}).click()
 assert.equal((await repeated).status(),200)
 await status.locator('textarea[name="body"]').waitFor()
 await customer.reload({waitUntil:'networkidle'})
 await history('We are keeping the manual export while we improve reporting.').getByText('Status update · declined',{exact:true}).waitFor()
 await history('Scheduled exports remain outside our current reporting plans.').getByText('Status update · declined',{exact:true}).waitFor()
 // An existing voter can still remove their vote; a new visitor cannot add one.
 await customer.getByRole('button',{name:'Remove vote',exact:true}).click()
 await customer.getByRole('status').filter({hasText:'Vote removed.'}).waitFor()
 assert.equal(await customer.getByRole('button',{name:'Vote',exact:true}).isDisabled(),true)
 await status.getByRole('button',{name:'Reverse decline',exact:true}).click()
 await status.getByText('Current public status: Planned · Direct status',{exact:true}).waitFor()
 await captureScreens(owner,'reversed',card)
 await customer.reload({waitUntil:'networkidle'})
 await history('We are keeping the manual export while we improve reporting.').getByText('Status update · declined',{exact:true}).waitFor()
 await history('Scheduled exports remain outside our current reporting plans.').getByText('Status update · declined',{exact:true}).waitFor()
 await customer.getByRole('button',{name:'Vote',exact:true}).click()
 await customer.getByRole('status').filter({hasText:'Vote saved.'}).waitFor()
 await customer.getByLabel('Add a comment',{exact:true}).fill('Thank you for reopening this discussion.')
 await customer.getByRole('button',{name:'Send comment for review',exact:true}).click()
 await customer.getByRole('status').filter({hasText:'Your comment is awaiting review.'}).waitFor()
 await captureScreens(customer,'customer-reopened')
 const result=await json(`/api/public/requests/${request.slug}`)
 assert.deepEqual(result.statusUpdates.filter(update=>update.status==='declined').map(update=>update.body).sort(),['Scheduled exports remain outside our current reporting plans.','We are keeping the manual export while we improve reporting.'])
 assert.equal(result.status,'planned');assert.equal(result.voteCount,1);assert.equal(result.comments.length,1)
})
