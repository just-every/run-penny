import assert from 'node:assert/strict'
import {moderationJourney} from './moderation-runtime.mjs'

await moderationJourney('import-statuses',async({origin,runtime,operator,json,pageFor,capture})=>{
 const owner=await pageFor({cookie:operator.Cookie})
 await owner.goto(origin+'/app/data',{waitUntil:'networkidle'})
 const panel=owner.locator('article').filter({has:owner.getByRole('heading',{name:'Move saved feedback in',exact:true})}).last()
 const csv='Post Title,Post Detail,Post Status,Date created,Post Author,Post URL\r\nSchedule monthly exports,Finance needs predictable exports.,Researching,2024-07-08T09:10:11Z,Avery Morgan,https://finance.canny.io/p/monthly-exports\r\n'
 await panel.getByLabel('Export file',{exact:true}).setInputFiles({name:'finance-statuses.csv',mimeType:'text/csv',buffer:Buffer.from(csv)})
 await panel.getByLabel('Penny board for these ideas',{exact:true}).fill('Finance history')
 await panel.getByLabel('Private board (only operators see it)',{exact:true}).uncheck()
 await panel.getByRole('combobox',{name:'Researching',exact:true}).selectOption('under_review')
 await panel.getByLabel('Keep source status names as internal statuses',{exact:true}).check()
 await capture(owner,'review-status-mapping',panel)
 await panel.getByRole('button',{name:'Preview saved feedback',exact:true}).click()
 await panel.getByRole('button',{name:'Apply reviewed import',exact:true}).waitFor()
 await capture(owner,'preview-status-import',panel)
 await panel.getByRole('button',{name:'Apply reviewed import',exact:true}).click()
 await panel.getByText('Import complete. Historical people have no sign-in or email permissions.',{exact:true}).waitFor()
 const boards=await json('/api/public/boards'),board=boards.find(b=>b.name==='Finance history')
 const {slug}=await runtime.db.prepare("SELECT slug FROM requests WHERE title='Schedule monthly exports'").first()
 await json(`/api/operator/moderation/${slug}`,{verdict:'approved',title:'Schedule monthly exports',description:'Finance needs predictable exports.',boardSlug:board.slug,displayName:'Avery Morgan'},operator)
 const visitor=await pageFor()
 await visitor.goto(origin+`/portal/feedback/${slug}`,{waitUntil:'networkidle'})
 assert.equal((await visitor.locator('main').innerText()).includes('Researching'),false)
 assert.equal((await json('/api/public/requests/'+slug)).status,'under_review')
 await capture(visitor,'mapped-public-status')
 await owner.goto(origin+'/app/settings',{waitUntil:'networkidle'})
 const form=owner.getByRole('form',{name:'Edit internal status Researching',exact:true})
 await form.locator('select[name="publicStatus"]').selectOption('planned')
 await form.getByLabel('Show this internal name publicly',{exact:true}).check()
 await form.getByRole('button',{name:'Save internal status',exact:true}).click()
 await form.getByText('Internal status saved.',{exact:true}).waitFor()
 await capture(owner,'imported-native-status',form)
 await visitor.reload({waitUntil:'networkidle'})
 await visitor.getByText('Researching',{exact:true}).first().waitFor()
 assert.equal((await json('/api/public/requests/'+slug)).status,'planned')
 await capture(visitor,'approved-custom-label')
})
