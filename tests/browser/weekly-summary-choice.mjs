import assert from 'node:assert/strict'

/** Native requester verification and settings; only runtime.outbox's mail edge is a fixture. */
export async function weeklySummaryChoice({browser,owner,runtime,viewport,inspect}) {
 const {origin}=runtime,setting=owner.getByRole('region',{name:'Weekly requester summary',exact:true})
 const ownerChoice=setting.getByRole('checkbox',{name:'Enable weekly requester summaries',exact:true})
 // An upgraded installation can have completed setup before postal admission.
 await runtime.db.prepare('DELETE FROM penny_mail_identity').run()
 await owner.goto(origin+'/app/settings#weekly-summary',{waitUntil:'networkidle'})
 await setting.getByRole('button',{name:'Save weekly summary setting',exact:true}).waitFor()
 assert.equal(await ownerChoice.isChecked(),false,'weekly summaries start off')
 await inspect('weekly-owner-off',setting)
 // SubmitFeedbackPage closes posting before rendering verification when no
 // requester-posting public board exists. Create that prerequisite natively.
 const board=await owner.context().request.post(origin+'/api/operator/boards',{headers:{Origin:origin},data:{slug:'reporting-workflows',name:'Reporting workflows',visibility:'public'}})
 assert.equal(board.status(),201,'owner creates the public requester-posting board')
 async function enable(value) {
  await ownerChoice.setChecked(value)
  const saved=owner.waitForResponse(response=>new URL(response.url()).pathname==='/api/operator/settings/weekly-summary'&&response.request().method()==='PUT')
  await setting.getByRole('button',{name:'Save weekly summary setting',exact:true}).click()
  assert.equal((await saved).status(),200)
  await setting.getByRole('status').filter({hasText:'setting saved'}).waitFor()
 }
 const context=await browser.newContext({viewport,extraHTTPHeaders:{'CF-Connecting-IP':'198.51.100.76'}}),errors=[]
 context.on('page',page=>{
  page.on('pageerror',error=>errors.push(error.message))
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text())})
  page.on('request',request=>{if(/^https?:/.test(request.url())&&new URL(request.url()).origin!==origin)errors.push('External browser request')})
 })
 try {
  const page=await context.newPage(),email='weekly-reader@example.test'
  // Portal appearance is fetched by the mounted layout effect, so it proves
  // client attachment before interacting with the server-rendered auth form.
  async function authDocument(url) {
   const ready=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/public/branding'&&response.request().method()==='GET')
   await page.goto(url,{waitUntil:'networkidle'})
   assert.equal((await ready).status(),200)
  }
  await authDocument(origin+'/portal/feedback/new')
  await page.getByRole('heading',{name:'Verify your email first',exact:true}).waitFor()
  await page.getByLabel('Display name',{exact:true}).fill('Jordan Rivera')
  await page.getByLabel('Email',{exact:true}).fill(email)
  const requested=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/public/identity/email'&&response.request().method()==='POST')
  await page.getByRole('button',{name:'Send verification link',exact:true}).click()
  assert.equal((await requested).status(),202)
  await page.getByText('Check your email for a verification link; it expires after 30 minutes.',{exact:true}).waitFor()
  const verification=runtime.outbox.findLast(message=>message.email===email)?.url
  assert.ok(verification,'the mail-edge fixture receives the native verification link')
  await authDocument(verification)
  await page.getByRole('button',{name:'Verify email',exact:true}).click()
  await page.getByText('Email verified.',{exact:true}).waitFor()
  const region=()=>page.getByRole('region',{name:'Weekly summary',exact:true})
  const choice=()=>region().getByRole('checkbox',{name:'Email me a weekly summary',exact:true})
  async function toggle(value) {
   const [response]=await Promise.all([
    page.waitForResponse(response=>new URL(response.url()).pathname==='/api/public/requester/weekly-summary'&&response.request().method()==='PATCH'),
    choice().setChecked(value),
   ])
   assert.equal(response.status(),200)
   assert.equal((await response.json()).subscribed,value)
   await region().getByRole('status').filter({hasText:value?'enabled.':'stopped.'}).waitFor()
  }
  await page.goto(origin+'/portal/feedback/activity',{waitUntil:'networkidle'})
  await choice().waitFor()
  assert.equal(await choice().isChecked(),false)
  assert.equal(await choice().isDisabled(),true,'owner-off prevents opting in')
  await inspect('weekly-activity-unavailable',region(),page)
  const custody=async()=>Object.fromEntries(await Promise.all(['penny_mail_identity','penny_weekly_summary','audit_entries','requester_update_permissions','notification_events','notification_intents','notification_batches','notification_attempts','notification_outbox','notification_outbox_attempts','notification_delivery_facts','penny_weekly_choices','penny_weekly_publications'].map(async table=>[table,(await runtime.db.prepare(`SELECT * FROM ${table} ORDER BY 1`).all()).results])))
  const before=await custody(),mailBeforeRefusal=structuredClone(runtime.outbox)
  await ownerChoice.check()
  const refused=owner.waitForResponse(response=>new URL(response.url()).pathname==='/api/operator/settings/weekly-summary'&&response.request().method()==='PUT')
  await setting.getByRole('button',{name:'Save weekly summary setting',exact:true}).click()
  const refusal=await refused
  assert.equal(refusal.status(),409)
  const reason=await refusal.json()
  assert.equal(reason.error,'postal_address_required')
  await setting.getByRole('status').filter({hasText:reason.message}).waitFor()
  assert.deepEqual(await custody(),before,'postal refusal changes no settings, audit, permissions or notifications')
  assert.deepEqual(runtime.outbox,mailBeforeRefusal,'postal refusal sends no mail')
  await inspect('weekly-owner-postal-required',setting)
  await owner.reload({waitUntil:'networkidle'})
  assert.equal(await ownerChoice.isChecked(),false,'postal refusal does not save enablement')
  await setting.getByRole('link',{name:'confirmed business postal address',exact:true}).click()
  const business=owner.getByRole('region',{name:'Email identity and postal address',exact:true})
  await business.getByLabel('Company name',{exact:true}).fill('Harbor Analytics')
  await business.getByLabel('Business postal address',{exact:true}).fill('125 High Street, Boston, MA 02110, USA')
  const confirmed=owner.waitForResponse(response=>new URL(response.url()).pathname==='/api/operator/settings/business'&&response.request().method()==='PUT')
  await business.getByRole('button',{name:'Confirm company and postal address',exact:true}).click()
  assert.equal((await confirmed).status(),200)
  await business.getByLabel('Business postal address',{exact:true}).waitFor()
  assert.equal(await runtime.db.prepare('SELECT postal_address FROM penny_mail_identity WHERE singleton=1').first('postal_address'),'125 High Street, Boston, MA 02110, USA')
  await inspect('weekly-owner-postal-confirmed',business)
  const {penny_weekly_summary:priorSetting,audit_entries:priorAudit,...priorEffects}=await custody(),mailBeforeEnable=structuredClone(runtime.outbox)
  assert.deepEqual(priorSetting,before.penny_weekly_summary,'postal confirmation alone does not enable weekly summaries')
  await enable(true)
  const {penny_weekly_summary:savedSetting,audit_entries:savedAudit,...savedEffects}=await custody()
  assert.deepEqual(savedEffects,priorEffects,'owner enablement creates no permission, notification or requester choice')
  assert.deepEqual(runtime.outbox,mailBeforeEnable,'owner enablement alone sends no mail')
  assert.equal(savedSetting.length,1)
  assert.equal(savedSetting[0].enabled,1)
  assert.ok(savedSetting[0].enabled_at)
  assert.deepEqual(savedAudit.filter(row=>priorAudit.some(prior=>prior.id===row.id)),priorAudit,'existing audit records survive enablement')
  const addedAudit=savedAudit.filter(row=>!priorAudit.some(prior=>prior.id===row.id))
  assert.equal(addedAudit.length,1,'enablement records one attributed settings change')
  const actor=await runtime.db.prepare("SELECT p.id FROM operators p JOIN oa_operators o ON o.email=p.email WHERE o.role='owner'").first('id')
  assert.deepEqual({actorType:addedAudit[0].actor_type,actor:addedAudit[0].actor_id,action:addedAudit[0].action,entity:addedAudit[0].entity_id,details:JSON.parse(addedAudit[0].details_json)},{actorType:'operator',actor,action:'notifications.weekly_setting',entity:'weekly-summary',details:{enabled:true}})
  await owner.reload({waitUntil:'networkidle'})
  assert.equal(await ownerChoice.isChecked(),true,'owner setting persists')
  await inspect('weekly-owner-on',setting)
  await page.reload({waitUntil:'networkidle'})
  await choice().waitFor()
  await toggle(true)
  await inspect('weekly-activity-opted-in',region(),page)
  await page.getByRole('link',{name:'Updates',exact:true}).click()
  await page.getByRole('heading',{name:'Product updates',exact:true}).waitFor()
  await choice().waitFor()
  assert.equal(await choice().isChecked(),true,'the same choice appears on updates')
  await page.reload({waitUntil:'networkidle'})
  await choice().waitFor()
  assert.equal(await choice().isChecked(),true,'requester choice survives reload')
  await inspect('weekly-updates-opted-in',region(),page)
  await enable(false)
  await page.reload({waitUntil:'networkidle'})
  await choice().waitFor()
  assert.equal(await choice().isChecked(),true)
  assert.equal(await choice().isDisabled(),false,'owner-off still permits opting out')
  await toggle(false)
  assert.equal(await choice().isDisabled(),true)
  await inspect('weekly-updates-opted-out',region(),page)
  await page.getByRole('link',{name:'Your feedback',exact:true}).click()
  await page.getByRole('heading',{name:'Your feedback',exact:true}).waitFor()
  await choice().waitFor()
  assert.equal(await choice().isChecked(),false,'updates opt-out is reflected on activity')
  await inspect('weekly-activity-opted-out',region(),page)
  assert.deepEqual(errors,[],'weekly choice has no browser errors or external requests')
  assert.deepEqual(await context.cookies(),[],'requester verification remains cookie-free')
  console.log(`[NOTIFY-010 NOTIFY-014] native postal refusal and recovery, owner setting, requester choice and owner-off opt-out passed at ${viewport.width}`)
 } finally {await context.close()}
}
