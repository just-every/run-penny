import assert from 'node:assert/strict'
export async function reviewRequesterOAuth({page,browser,runtime,width,goto,capture}){
 const origin=runtime.origin
 const api=async(path,body,method=body===undefined?'GET':'POST')=>{const response=await page.request.fetch(origin+path,{method,headers:{Origin:origin},...(body===undefined?{}:{data:body})});assert.ok(response.ok(),path+': '+response.status());return response.json()}
 await api('/api/operator/boards',{name:'Synthetic feedback',slug:'synthetic-penny',visibility:'public'})
 const boards=await api('/api/public/boards');await api('/api/operator/boards/synthetic-penny/vote-subscriptions',{enabled:false,version:boards.find(row=>row.slug==='synthetic-penny').subscriptionDisclosure.version},'PUT')
 const request=await api('/api/operator/requests',{title:'Schedule synthetic reports',description:'Prepare monthly reports',boardSlug:'synthetic-penny',evidenceIds:[]})
 await api(`/api/operator/moderation/${request.slug}`,{verdict:'approved',title:'Schedule synthetic reports',description:'Prepare monthly reports',boardSlug:'synthetic-penny',displayName:'Product team'})
 await goto('/app/settings')
 const panel=page.locator('section[aria-labelledby=requester-oauth]')
 await panel.getByLabel('Continue with Google',{exact:true}).waitFor()
 assert.equal(await panel.getByLabel('Continue with Google',{exact:true}).isChecked(),false)
 assert.equal(await panel.getByLabel('Continue with GitHub',{exact:true}).isChecked(),false)
 await capture('REQ-039-owner-off')
 const requester=await browser.newContext({viewport:{width,height:width===390?844:900}}),customer=await requester.newPage(),cookies=[],errors=[]
 customer.on('response',response=>{if(response.headers()['set-cookie'])cookies.push(new URL(response.url()).pathname)})
 customer.on('pageerror',error=>errors.push(error.message))
 try{
  await customer.goto(origin+'/portal/feedback/new')
  await customer.getByRole('button',{name:'Send verification link',exact:true}).waitFor()
  assert.equal(await customer.getByRole('button',{name:/Continue with Google|Continue with GitHub/}).count(),0)
  await capture('REQ-039-providers-off',customer)
  await panel.getByLabel('Continue with Google',{exact:true}).check();await panel.getByLabel('Continue with GitHub',{exact:true}).check()
  const saved=page.waitForResponse(r=>r.url().endsWith('/api/operator/settings/requester-oauth')&&r.request().method()==='PUT')
  await panel.getByRole('button',{name:'Save social sign-in settings',exact:true}).click();assert.equal((await saved).status(),200)
  await panel.getByText('Requester sign-in settings saved.',{exact:true}).waitFor();await capture('REQ-039-owner-enabled')
  await requester.route(url=>(url.origin==='https://accounts.google.com'&&url.pathname==='/o/oauth2/v2/auth')||(url.origin==='https://github.com'&&url.pathname==='/login/oauth/authorize'),async route=>{
   const url=new URL(route.request().url()),provider=url.host==='accounts.google.com'?'google':'github'
   assert.ok(url.searchParams.get('code_challenge'));assert.equal(url.searchParams.get('code_challenge_method'),'S256')
   const callback=new URL(url.searchParams.get('redirect_uri'));assert.equal(callback.origin,origin)
   callback.search=new URLSearchParams({state:url.searchParams.get('state'),code:'synthetic-penny-browser-code'}).toString()
   await route.fulfill({status:302,headers:{Location:callback.href},body:''})
  })
  await customer.goto(origin+`/portal/feedback/${request.slug}`)
  await customer.getByRole('button',{name:'Vote',exact:true}).click()
  await customer.waitForURL(origin+'/portal/feedback/new')
  await customer.getByRole('button',{name:'Continue with Google',exact:true}).waitFor();await capture('REQ-039-verification-choice',customer)
  await customer.getByRole('button',{name:'Continue with Google',exact:true}).click()
  await customer.waitForURL(origin+`/portal/feedback/${request.slug}`)
  await customer.getByRole('button',{name:'Remove vote',exact:true}).waitFor()
  assert.equal(await customer.locator('input[type=checkbox]:checked').count(),0)
  assert.equal(await runtime.db.prepare('SELECT count(*) n FROM requester_update_permissions').first('n'),0)
  assert.deepEqual(await requester.cookies(),[]);assert.deepEqual(cookies,[])
  await capture('REQ-039-google-returned-vote',customer)
  await customer.evaluate(()=>localStorage.removeItem('penny_requester_session'))
  await customer.goto(origin+'/portal/feedback/new')
  await customer.getByRole('button',{name:'Continue with GitHub',exact:true}).click()
  await customer.getByText('Check your email for a verification link. Nothing has been applied yet.',{exact:true}).waitFor()
  assert.equal(await runtime.db.prepare("SELECT count(*) n FROM requester_addresses WHERE email='synthetic-penny-github@example.test'").first('n'),0)
  assert.ok(runtime.outbox.some(row=>row.email==='synthetic-penny-github@example.test'))
  await capture('REQ-039-github-email-fallback',customer)
  assert.deepEqual(await requester.cookies(),[]);assert.deepEqual(cookies,[]);assert.deepEqual(errors,[])
 }finally{await requester.close()}
 await api('/api/operator/settings/requester-oauth',{google:false,github:false},'PUT')
 await runtime.configure({REQUESTER_GOOGLE_CLIENT_SECRET:''})
 await goto('/app/settings')
 assert.equal(await panel.getByLabel('Continue with Google',{exact:true}).count(),0,'a provider without its installation credentials is not offered')
 const refused=await page.request.fetch(origin+'/api/operator/settings/requester-oauth',{method:'PUT',headers:{Origin:origin},data:{google:true,github:false}});assert.equal(refused.status(),409)
 await capture('REQ-039-owner-binding-required')
}
