import assert from 'node:assert/strict'
import {moderationJourney} from './moderation-runtime.mjs'
await moderationJourney('proxy-votes',async({runtime,origin,operator,json,send,person,pageFor,capture})=>{
 const customer=await person('eli@example.test','Eli Wong'),auth={Authorization:`Bearer ${customer.token}`}
 const request=await json('/api/public/requests',{title:'Schedule monthly finance exports',description:'Finance needs a monthly CSV for its board review.',boardSlug:'finance',idempotencyKey:crypto.randomUUID()},auth,'POST',201)
 await json(`/api/operator/moderation/${request.slug}`,{verdict:'approved',title:'Schedule monthly finance exports',description:'Schedule monthly exports for finance reviews.',boardSlug:'finance',displayName:'Eli Wong'},operator)
 const evidence=await json('/api/operator/evidence',{sourceType:'support_conversation',wording:'Sam needs monthly exports for the finance review.',observedAt:new Date().toISOString()},operator,'POST',201)
 const owner=await pageFor({cookie:operator.Cookie}),visitor=await pageFor()
 await owner.goto(origin+'/app/feedback',{waitUntil:'networkidle'})
 const item=owner.locator(`#evidence-${evidence.id}`)
 await item.getByText('Record a customer’s vote',{exact:true}).click()
 await item.getByLabel('Create a new unverified contact').check()
 await item.getByLabel('Customer display name',{exact:true}).fill('Sam Rivera')
 await item.getByLabel('Customer email (optional, remains unverified)').fill('sam@example.test')
 await item.getByLabel('Source justifying this vote').fill('Zendesk ticket 738: requested during monthly finance review')
 await item.getByLabel('Original source URL (optional)').fill('https://harbor.zendesk.com/agent/tickets/738')
 await capture(owner,'inbox-proxy-form',item)
 await item.getByRole('button',{name:'Record proxy vote',exact:true}).click()
 await item.getByRole('status').filter({hasText:'Customer vote recorded'}).waitFor()
 await owner.goto(origin+`/app/moderation?q=Schedule%20monthly`,{waitUntil:'networkidle'})
 const card=owner.locator('article').filter({has:owner.getByRole('heading',{name:'Schedule monthly finance exports',exact:true})}).first()
 await card.getByText('Supporters (2)',{exact:true}).click()
 await card.getByText('Proxy vote',{exact:true}).waitFor()
 await card.getByRole('link',{name:'Original source',exact:true}).waitFor()
 await card.getByText('Sam Rivera',{exact:true}).scrollIntoViewIfNeeded()
 await capture(owner,'request-proxy-attribution',card.getByRole('list',{name:'Supporters',exact:true}))
 assert.equal(await runtime.db.prepare('SELECT verified_at FROM requester_addresses WHERE email=?').bind('sam@example.test').first('verified_at'),null)
 const contact=await runtime.db.prepare('SELECT requester_id FROM requester_addresses WHERE email=?').bind('sam@example.test').first('requester_id')
 assert.equal(await runtime.db.prepare('SELECT COUNT(*) n FROM requester_update_permissions WHERE requester_id=?').bind(contact).first('n'),0)
 // The request control can select an existing customer and records no second vote.
 await card.getByText('Record a customer’s vote',{exact:true}).click()
 await card.getByLabel('Find an existing customer').fill('sam@example.test')
 await card.getByRole('button',{name:'Find customer',exact:true}).click()
 await card.getByRole('combobox',{name:/Existing customer/}).selectOption(contact).catch(async error=>{await capture(owner,'customer-search-failure');throw error})
 await card.getByLabel('Source justifying this vote').fill('Repeated conversation, same customer')
 await card.getByRole('button',{name:'Record proxy vote',exact:true}).click()
 await card.getByRole('status').filter({hasText:'already supports'}).waitFor()
 await capture(owner,'duplicate-proxy-refused')
 await json('/api/operator/boards/finance',{showVoters:true},operator,'PATCH')
 await visitor.goto(origin+`/portal/feedback/${request.slug}`,{waitUntil:'networkidle'})
 assert.equal((await visitor.content()).includes('Sam Rivera'),false)
 assert.equal((await visitor.content()).includes('738'),false)
 await capture(visitor,'public-proxy-total')
 const csv=await send('/api/operator/votes/export.csv',undefined,operator)
 const csvText=await csv.text();assert.match(csvText,/Sam Rivera.*yes/);assert.ok(!csvText.includes('sam@example.test'))
})
