import assert from 'node:assert/strict'
import {form,save} from './loopjourney-steps.mjs'
import {waitForReviewNotification} from './loopjourney-review-notification.mjs'
export async function clauseDecisions(operator,runtime,commit,releaseSlug,audit,accountContext){
 const {origin}=runtime
 await operator.goto(origin+`/app/decisions/${commit.decisionSlug}`,{waitUntil:'networkidle'})
 const postRelease=operator.locator('section').filter({has:operator.getByRole('heading',{name:'Post-release evidence',exact:true})})
 await postRelease.getByRole('heading',{name:'Post-release evidence',exact:true}).waitFor()
 await postRelease.locator('ol').getByText('Requester outcome · adopted',{exact:true}).waitFor()
 await audit(operator,'DEC-008-post-release-outcome-timeline')
 const review=form(operator,'Complete decision review')
 await review.getByLabel('Review note',{exact:true}).fill('We reviewed adoption and will check again after more teams use it.')
 await review.getByLabel('Next review date',{exact:true}).fill('2020-01-01')
 await audit(operator,'DEC-007-review-form')
 await save(operator,review,'Record review',`/api/operator/decisions/${commit.decisionId}/reviews`)
 await waitForReviewNotification(operator,runtime,commit,audit)
 const notices=operator.locator('details').filter({has:operator.getByText(/^Review notifications/)}).first()
 await notices.locator('summary').click()
 const notification=form(notices,'Decision review due')
 await notification.waitFor()
 assert.equal(await notification.count(),1,'[NOTIFY-003] the real minute Cron creates one in-app owner notification')
 await audit(operator,'DEC-007-NOTIFY-003-review-due-notification')
 await notification.getByRole('button',{name:'Dismiss notification',exact:true}).click()
 await notices.getByText('No review notifications.',{exact:true}).waitFor()
 await audit(operator,'NOTIFY-003-notification-dismissed')
 const history=operator.getByRole('region',{name:'Decision revision and review',exact:true}).locator('section').filter({has:operator.getByRole('heading',{name:'Commitment and review history',exact:true})})
 const original=history.locator('details').last()
 const originalLabel=await original.locator('summary').innerText()
 await original.locator('summary').click()
 await original.getByRole('heading',{name:'Evidence snapshot at commitment',exact:true}).waitFor()
 await original.locator('ul > li').first().waitFor()
 const originalSnapshot=await original.locator('ul').innerText()
 const revision=form(operator,'Revise commitment')
 const revisedRationale='Adoption evidence supports continuing the selected approach with revised rationale.'
 await revision.getByLabel('Revised rationale',{exact:true}).fill(revisedRationale)
 await revision.getByLabel('Revision review date',{exact:true}).fill('2027-01-01')
 await revision.getByLabel('Revision review note',{exact:true}).fill('Reviewed the release outcomes and revised the rationale.')
 await audit(operator,'DEC-006-revision-form')
 await save(operator,revision,'Commit new revision',`/api/operator/decisions/${commit.decisionId}/reviews`)
 const revised=history.locator('details').filter({has:operator.getByText(revisedRationale,{exact:true})})
 await revised.locator('summary').click()
 await revised.getByRole('heading',{name:'Evidence snapshot at commitment',exact:true}).waitFor()
 await audit(operator,'DEC-006-commitment-history-snapshot')
 await operator.goto(origin+'/app/feedback',{waitUntil:'networkidle'})
 const recorder=form(operator,'New evidence')
 const releases=await operator.request.get(origin+`/api/operator/releases/${releaseSlug}`).then(response=>response.json())
 await recorder.getByLabel('Source',{exact:true}).selectOption('support_conversation')
 const postReleaseWording='After release, the onboarding progress view reduced support questions.'
 await recorder.getByLabel('Original wording',{exact:true}).fill(postReleaseWording)
 const now=new Date();now.setMinutes(now.getMinutes()-now.getTimezoneOffset())
 await recorder.getByLabel('Observed time',{exact:true}).fill(now.toISOString().slice(0,16))
 await recorder.getByLabel('Linked release ID (optional)',{exact:true}).fill(releases.id)
 await recorder.getByLabel('Existing account (optional)',{exact:true}).selectOption(accountContext.accountId)
 const brief=await operator.request.get(origin+`/api/operator/decisions/${commit.decisionSlug}`).then(response=>response.json())
 await recorder.getByLabel('Candidate bet (optional)',{exact:true}).selectOption(brief.selectedCandidateBetId)
 await save(operator,recorder,'Record evidence','/api/operator/evidence')
 await operator.goto(origin+`/app/decisions/${commit.decisionSlug}`,{waitUntil:'networkidle'})
 const recorded=postRelease.locator('ol > li').filter({has:operator.getByText(postReleaseWording,{exact:true})})
 await recorded.getByText(postReleaseWording,{exact:true}).waitFor()
 await recorded.getByRole('link',{name:'Original evidence',exact:true}).waitFor()
 const preserved=history.locator('details').filter({has:operator.getByText(originalLabel,{exact:true})})
 await preserved.locator('summary').click()
 await preserved.getByRole('heading',{name:'Evidence snapshot at commitment',exact:true}).waitFor()
 assert.equal(await preserved.locator('ul').innerText(),originalSnapshot,'[DEC-006/DEC-008] the original commitment retains its evidence wording, stances and version identities after revision and post-release evidence')
 assert.equal(await preserved.locator('ul').getByText(postReleaseWording,{exact:true}).count(),0,'[DEC-008] new post-release evidence stays outside the original commitment snapshot')
 await audit(operator,'DEC-008-post-release-recorded-evidence')
 await operator.goto(origin+`/app/customers/${accountContext.accountSlug}`,{waitUntil:'networkidle'})
 const accountDecision=operator.getByRole('region',{name:'Linked decisions',exact:true}).getByRole('link').filter({has:operator.getByText(brief.title,{exact:true})})
 await accountDecision.waitFor()
 assert.equal(await accountDecision.getAttribute('href'),`/app/decisions/${commit.decisionSlug}`,'[EVID-005] the account links the committed decision by its saved slug')
 await audit(operator,'EVID-005-account-complete-requesters-evidence-decision-links')
}
