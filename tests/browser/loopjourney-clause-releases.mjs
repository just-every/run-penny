import { form,save } from './loopjourney-steps.mjs'
export async function clauseReleases(operator,requester,origin,slug,audit,requesterAudit){
 await requester.goto(origin+'/portal/updates',{waitUntil:'networkidle'})
 await requester.getByRole('button',{name:'Subscribe to product updates',exact:true}).click()
 await requester.getByRole('button',{name:'Unsubscribe from product updates',exact:true}).waitFor()
 await requesterAudit(requester,'REL-012-subscribed-all-updates')
 await requester.getByRole('button',{name:'Unsubscribe from product updates',exact:true}).click()
 await requester.getByRole('button',{name:'Subscribe to product updates',exact:true}).waitFor()
 await requesterAudit(requester,'REL-012-unsubscribed-all-updates')
 await requester.goto(origin+`/portal/updates/${slug}`,{waitUntil:'networkidle'})
 const outcomes=requester.getByRole('region',{name:'Release outcomes'})
 const target=outcomes.locator('select').first()
 await target.waitFor()
 await target.selectOption('adopted')
 await requesterAudit(requester,'REL-008-outcome-form')
 await save(requester,outcomes,'Save outcomes',`/api/public/releases/${slug}/outcomes`)
 await outcomes.getByText('Your outcomes are saved.',{exact:true}).waitFor()
 await requesterAudit(requester,'REL-008-adopted-outcome')
 await target.selectOption('partly_adopted')
 await save(requester,outcomes,'Save outcomes',`/api/public/releases/${slug}/outcomes`)
 await requesterAudit(requester,'REL-008-outcome-revised')
 await operator.goto(origin+`/app/releases/${slug}`,{waitUntil:'networkidle'})
 await operator.getByText('Individual responses · operator-only',{exact:true}).waitFor()
 await audit(operator,'REL-009-private-coverage-context-links')
 const correction=form(operator,'Correct published release')
 await correction.getByLabel('Corrected title',{exact:true}).fill('Onboarding progress is live — corrected')
 await correction.getByLabel('Corrected body',{exact:true}).fill('You can see each onboarding step, with refreshed setup instructions.')
 await audit(operator,'REL-003-correction-form')
 const result=await save(operator,correction,'Publish correction',`/api/operator/releases/${slug}/corrections`)
 await operator.getByText('Earlier version',{exact:false}).first().waitFor()
 await audit(operator,'REL-003-correction-history-unsent')
 const send=form(operator,'Send this release version').first()
 await save(operator,send,'Send version to recipients',`/api/operator/releases/${slug}/versions/${result.versionId}/deliver`)
 await operator.getByText('This version has already been queued for delivery.',{exact:true}).first().waitFor()
 await audit(operator,'REL-003-corrected-version-delivery')
 await requester.goto(origin+`/portal/updates/${slug}`,{waitUntil:'networkidle'})
 await requester.getByRole('heading',{name:'Onboarding progress is live — corrected',exact:true}).waitFor()
 await requesterAudit(requester,'REL-003-public-current-version')
}
