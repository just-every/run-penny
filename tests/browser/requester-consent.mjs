import assert from 'node:assert/strict'
import {expect} from '@playwright/test'
import {shot} from './requester-evidence.mjs'

export async function proveRequesterConsent(harness){
 const {origin,api,sql}=harness,operator=await harness.operator(1440)
 for(const slug of ['consent-explicit','consent-automatic'])await api('/api/operator/boards',{slug,name:slug==='consent-explicit'?'Explicit consent':'Automatic subscriptions',visibility:'public'},operator.page.request)
 await harness.explicitConsentBoard('consent-explicit',operator.page.request)
 const boards=await (await api('/api/public/boards')).json(),automatic=boards.find(board=>board.slug==='consent-automatic').subscriptionDisclosure
 assert.equal(automatic.enabled,true)
 assert.match(automatic.vote,/voting subscribes.*unfollow/i)
 assert.match(automatic.submission,/updates.*unfollow/i)
 const author=await harness.requester(1440,['synthetic-penny-1','example.test'].join('@'))
 const voter=await harness.requester(1440,['synthetic-penny-2','example.test'].join('@'))
 const authority=person=>({Authorization:`Bearer ${person.token}`,'CF-Connecting-IP':person.clientAddress})
 const activity=async person=>(await api('/api/public/requester/activity',undefined,authority(person))).json()
 const permissions=async person=>sql(`SELECT p.* FROM requester_update_permissions p JOIN requester_addresses a ON a.id=p.requester_address_id WHERE a.email='${person===author?['synthetic-penny-1','example.test'].join('@'):['synthetic-penny-2','example.test'].join('@')}' ORDER BY p.id`)
 async function screens(page,label){
  await shot(page,label,1440)
  await page.setViewportSize({width:390,height:844})
  try{await shot(page,label,390)}finally{await page.setViewportSize({width:1440,height:1000})}
 }
 async function submit(board,title,checked=false){
  const page=author.page
  await page.goto(origin+'/portal/feedback/new')
  await page.getByLabel('Title',{exact:true}).fill(title)
  await page.getByLabel('Problem description',{exact:true}).fill('Customers need a reliable scheduled report.')
  await page.locator('select[name=board]').selectOption(board)
  const control=page.getByRole('checkbox',{name:'Email me updates',exact:true})
  await expect(control).not.toBeChecked()
  if(board==='consent-automatic')await expect(page.getByText(automatic.submission,{exact:true})).toBeVisible()
  else await expect(page.getByText(automatic.submission,{exact:true})).toHaveCount(0)
  if(checked)await control.check()
  if(!checked)await screens(page,board+'-submission')
  const saved=page.waitForResponse(response=>new URL(response.url()).pathname==='/api/public/requests'&&response.request().method()==='POST')
  await page.getByRole('button',{name:'Send for review',exact:true}).click()
  const response=await saved;assert.equal(response.status(),201,await response.text())
  await page.getByRole('heading',{name:'Feedback is awaiting review',exact:true}).waitFor()
  const request=(await activity(author)).requests.find(request=>request.title===title)
  assert.ok(request)
  await api(`/api/operator/moderation/${request.slug}`,{verdict:'approved',title,description:'Customers need a reliable scheduled report.',boardSlug:board,displayName:'Verified customer'},operator.page.request)
  return request
 }
 const plain=await submit('consent-explicit','Schedule a customer report')
 assert.deepEqual(await permissions(author),[])
 assert.deepEqual((await activity(author)).follows,[])
 const checked=await submit('consent-explicit','Choose update emails explicitly',true)
 assert.deepEqual((await permissions(author)).map(row=>[row.request_id,row.source,row.grant_origin]),[[checked.id,'submission','explicit']])
 const automaticRequest=await submit('consent-automatic','Subscribe to report progress')
 assert.ok((await permissions(author)).some(row=>row.request_id===automaticRequest.id&&row.grant_origin==='author_subscription'&&row.setting_version===automatic.version))
 assert.ok((await activity(author)).follows.some(row=>row.slug===automaticRequest.slug))
 const page=voter.page,participation=page.getByRole('region',{name:'Participate in feedback',exact:true})
 await page.goto(origin+`/portal/feedback/${plain.slug}`)
 const control=participation.getByRole('checkbox',{name:'Email me updates',exact:true}),vote=participation.getByRole('button',{name:'Vote',exact:true})
 await expect(vote).toBeEnabled();await expect(control).not.toBeChecked()
 await expect(participation.getByText(automatic.vote,{exact:true})).toHaveCount(0)
 await screens(page,'consent-explicit-vote')
 await vote.click();await participation.getByText('Vote saved.',{exact:true}).waitFor()
 assert.deepEqual(await permissions(voter),[])
 assert.ok((await activity(voter)).votes.some(row=>row.slug===plain.slug))
 assert.deepEqual((await activity(voter)).follows,[])
 await participation.getByRole('button',{name:'Remove vote',exact:true}).click()
 await participation.getByText('Vote removed.',{exact:true}).waitFor()
 await control.check();await vote.click()
 await expect(participation.getByRole('button',{name:'Unfollow',exact:true})).toBeEnabled()
 assert.deepEqual((await permissions(voter)).map(row=>[row.request_id,row.source,row.grant_origin]),[[plain.id,'vote','explicit']])
 await participation.getByRole('button',{name:'Unfollow',exact:true}).click()
 await participation.getByText('Unfollowed.',{exact:true}).waitFor()
 assert.deepEqual((await activity(voter)).follows,[])
 assert.ok((await permissions(voter)).every(row=>row.revoked_at))
 await participation.getByRole('button',{name:'Follow',exact:true}).click()
 await participation.getByText('Following with email permission.',{exact:true}).waitFor()
 assert.ok((await permissions(voter)).some(row=>row.request_id===plain.id&&row.source==='follow'&&row.revoked_at===null))
 await page.goto(origin+`/portal/feedback/${automaticRequest.slug}`)
 await expect(vote).toBeEnabled();await expect(control).not.toBeChecked()
 await expect(participation.getByText(automatic.vote,{exact:true})).toBeVisible()
 await screens(page,'consent-automatic-vote')
 await vote.click()
 await expect(participation.getByRole('button',{name:'Unfollow',exact:true})).toBeEnabled()
 assert.ok((await activity(voter)).follows.some(row=>row.slug===automaticRequest.slug))
 assert.ok((await permissions(voter)).some(row=>row.request_id===automaticRequest.id&&row.grant_origin==='vote_subscription'&&row.setting_version===automatic.version))
 await page.reload()
 await expect(participation.getByRole('button',{name:'Unfollow',exact:true})).toBeEnabled()
 await participation.getByRole('button',{name:'Unfollow',exact:true}).click()
 await participation.getByText('Unfollowed.',{exact:true}).waitFor()
 assert.ok(!(await activity(voter)).follows.some(row=>row.slug===automaticRequest.slug))
 assert.ok((await permissions(voter)).filter(row=>row.request_id===automaticRequest.id).every(row=>row.revoked_at))
 const checks={uncheckedSubmission:true,uncheckedVote:true,untickedActionsGrantNothing:true,currentAutomaticDisclosures:true,checkedSubmission:true,checkedVote:true,explicitFollow:true,automaticAuthorFollow:true,automaticVoterFollow:true,unfollowRevokes:true}
 harness.assertNoRateLimits();harness.assertNoBrowserDiagnostics()
 console.log('PROBE REQ-010 point 1: mounted submission and vote controls -> unchecked; ordinary actions grant nothing; current disclosures lead to automatic follows')
 console.log('PROBE REQ-010 point 2: checked submission, checked vote and Follow -> persisted explicit permissions; Unfollow -> revoked permission and absent activity follow')
 await author.context.close();await voter.context.close();await operator.context.close()
 return checks
}
