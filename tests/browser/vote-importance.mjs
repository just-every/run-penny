import assert from 'node:assert/strict'
import {moderationJourney} from './moderation-runtime.mjs'
await moderationJourney('vote-importance',async({runtime,origin,operator,json,person,pageFor,capture})=>{
 const author=await person('eli@example.test','Eli Wong'),voter=await person('morgan@example.test','Morgan Reed')
 const request=await json('/api/public/requests',{title:'Schedule monthly finance exports',description:'Finance needs a monthly CSV for its board review.',boardSlug:'finance',idempotencyKey:crypto.randomUUID()},{Authorization:`Bearer ${author.token}`},'POST',201)
 await json(`/api/operator/moderation/${request.slug}`,{verdict:'approved',title:'Schedule monthly finance exports',description:'Schedule monthly exports for finance reviews.',boardSlug:'finance',displayName:'Eli Wong'},operator)
 const owner=await pageFor({cookie:operator.Cookie}),customer=await pageFor({token:voter.token}),visitor=await pageFor()
 await owner.goto(origin+'/app/settings',{waitUntil:'networkidle'})
 await owner.getByText('Vote importance',{exact:true}).click()
 await owner.getByLabel('Ask voters for importance',{exact:true}).check()
 await owner.getByLabel('Importance level 4 (optional)',{exact:true}).fill('Critical')
 await owner.getByRole('button',{name:'Save importance settings',exact:true}).click()
 await owner.getByRole('status').filter({hasText:'Vote importance settings saved.'}).waitFor()
 const settings=owner.locator('details').filter({has:owner.getByText('Vote importance',{exact:true})})
 await settings.scrollIntoViewIfNeeded()
 await capture(owner,'importance-board-settings',settings)
 await customer.goto(origin+`/portal/feedback/${request.slug}`,{waitUntil:'networkidle'})
 const choice=customer.getByRole('combobox',{name:/How important is this to you/})
 await choice.selectOption('3')
 await customer.getByRole('button',{name:'Vote',exact:true}).click()
 await customer.getByRole('button',{name:'Remove vote',exact:true}).waitFor()
 await customer.getByRole('button',{name:'Save importance',exact:true}).waitFor()
 await capture(customer,'requester-must-have')
 await owner.goto(origin+'/app/moderation?q=Schedule%20monthly',{waitUntil:'networkidle'})
 const card=owner.locator('article').filter({has:owner.getByRole('heading',{name:'Schedule monthly finance exports',exact:true})}).first()
 const breakdown=card.getByRole('region',{name:'Vote importance breakdown',exact:true})
 await breakdown.waitFor()
 assert.deepEqual(await breakdown.locator('dd').allTextContents(),['0','0','1','0','1'])
 await breakdown.scrollIntoViewIfNeeded()
 await capture(owner,'operator-must-have',breakdown)
 await choice.selectOption('2')
 await customer.getByRole('button',{name:'Save importance',exact:true}).click()
 await customer.getByRole('status').filter({hasText:'Importance saved.'}).waitFor()
 await owner.reload({waitUntil:'networkidle'})
 assert.deepEqual(await breakdown.locator('dd').allTextContents(),['0','1','0','0','1'])
 await breakdown.scrollIntoViewIfNeeded()
 await capture(owner,'operator-important',breakdown)
 await choice.selectOption('')
 await customer.getByRole('button',{name:'Save importance',exact:true}).click()
 await customer.getByRole('status').filter({hasText:'Importance saved.'}).waitFor()
 await customer.reload({waitUntil:'networkidle'})
 assert.equal(await choice.inputValue(),'')
 await capture(customer,'requester-cleared-importance')
 await owner.reload({waitUntil:'networkidle'})
 await card.getByText('Record a customer’s vote',{exact:true}).click()
 await card.getByLabel('Create a new unverified contact').check()
 await card.getByLabel('Customer display name',{exact:true}).fill('Taylor Chen')
 await card.getByLabel('Customer’s stated importance (optional)').selectOption('4')
 await card.getByLabel('Source justifying this vote').fill('Taylor called this critical for the next finance review.')
 await capture(owner,'proxy-stated-importance',card.getByRole('button',{name:'Record proxy vote',exact:true}).locator('..'))
 await card.getByRole('button',{name:'Record proxy vote',exact:true}).click()
 await card.getByRole('status').filter({hasText:'Customer vote recorded'}).waitFor()
 await breakdown.locator('dd').nth(3).filter({hasText:/^1$/}).waitFor()
 assert.deepEqual(await breakdown.locator('dd').allTextContents(),['0','0','0','1','2'])
 await breakdown.scrollIntoViewIfNeeded()
 await capture(owner,'proxy-critical-importance',breakdown)
 await visitor.goto(origin+`/portal/feedback/${request.slug}`,{waitUntil:'networkidle'})
 const bytes=JSON.stringify(await json('/api/public/requests/'+request.slug))
 for(const value of ['importance','Critical','Taylor Chen'])assert.equal(bytes.includes(value),false)
 assert.equal(await visitor.getByRole('combobox',{name:/How important is this to you/}).count(),0)
 await capture(visitor,'public-importance-privacy')
 // A prepared saved Canny bundle uses the real importer UI and names each enum in its receipt.
 const created='2024-07-08T09:10:11Z',priorities=['Nice to have','Important','Must have','No priority'],users=priorities.map((_,i)=>({id:'historical-'+i,name:['Avery Morgan','Jordan Park','Casey Bell','Robin Shaw'][i],created}))
 const source={namespace:'finance-vote-priorities',statuses:{open:'open'},boards:[{id:'history',name:'Finance history',isPrivate:false,created}],files:[
  {name:'posts.json',kind:'posts',version:'v1',base64:Buffer.from(JSON.stringify({posts:[{id:'historical-export',title:'Keep monthly export templates',details:'Reuse finance templates each month.',status:'open',board:'history',author:users[0],created}]})).toString('base64')},
  {name:'votes.json',kind:'votes',version:'v2',base64:Buffer.from(JSON.stringify({items:priorities.map((votePriority,i)=>({id:'vote-'+i,post:'historical-export',voter:users[i],created,votePriority}))})).toString('base64')},
 ]}
 await owner.goto(origin+'/app/data',{waitUntil:'networkidle'})
 const panel=owner.locator('article').filter({has:owner.getByRole('heading',{name:'Move saved feedback in',exact:true})}).last()
 await panel.getByRole('combobox',{name:/What did you export/}).selectOption('bundle')
 await panel.getByLabel('Prepared saved feedback bundle',{exact:true}).setInputFiles({name:'finance-vote-priorities.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(source))})
 await panel.getByRole('button',{name:'Preview saved feedback',exact:true}).click()
 await panel.getByRole('button',{name:'Apply reviewed import',exact:true}).waitFor()
 const preview=panel.getByRole('region',{name:'Imported vote importance',exact:true}).first()
 await preview.scrollIntoViewIfNeeded()
 await capture(owner,'canny-importance-preview',preview)
 await panel.getByRole('button',{name:'Apply reviewed import',exact:true}).click()
 await panel.getByText('Import complete. Historical people have no sign-in or email permissions.',{exact:true}).waitFor()
 const receipt=panel.getByRole('region',{name:'Imported vote importance',exact:true}).last()
 await receipt.scrollIntoViewIfNeeded()
 await capture(owner,'canny-importance-receipt',receipt)
 assert.equal(await runtime.db.prepare('SELECT COUNT(*) n FROM penny_vote_importance WHERE request_id IN(SELECT id FROM requests WHERE title=?)').bind('Keep monthly export templates').first('n'),4)
})
