import assert from 'node:assert/strict'
import {moderationJourney} from './moderation-runtime.mjs'

await moderationJourney('import-board-policy',async({origin,runtime,operator,json,send,person,pageFor,capture})=>{
 const shot=async(page,label,region)=>{await page.evaluate(()=>window.scrollTo(0,0));await capture(page,label,region)}
 const owner=await pageFor({cookie:operator.Cookie})
 await owner.goto(origin+'/app/data',{waitUntil:'networkidle'})
 const panel=owner.locator('section').filter({has:owner.getByRole('heading',{name:'Move saved feedback in',exact:true})}).last()
 const csv='Post Title,Post Detail,Post Status,Date created,Post Author,Post URL\r\nSchedule monthly finance exports,Make exports available before the monthly review.,open,2024-07-08T09:10:11Z,Source customer,https://finance.canny.io/p/monthly-exports\r\n'
 await panel.getByLabel('Export file',{exact:true}).setInputFiles({name:'finance-export.csv',mimeType:'text/csv',buffer:Buffer.from(csv)})
 await panel.getByLabel('Penny board for these ideas',{exact:true}).fill('Finance history')
 await panel.getByLabel('Private board (only operators see it)',{exact:true}).uncheck()
 await panel.getByLabel('Map this board’s participation and display settings',{exact:true}).check()
 await shot(owner,'policy-options')
 await panel.getByRole('combobox',{name:/Who may post/}).selectOption('operators')
 await panel.getByLabel('Show vote totals publicly',{exact:true}).uncheck()
 await panel.getByLabel('List voter display names publicly',{exact:true}).check()
 await panel.getByLabel('Show requester names as Anonymous',{exact:true}).check()
 await shot(owner,'review-board-policy',panel.locator('fieldset').filter({has:owner.getByText('Board participation and display',{exact:true})}))
 await panel.getByRole('button',{name:'Preview saved feedback',exact:true}).click()
 await panel.getByRole('button',{name:'Apply reviewed import',exact:true}).waitFor()
 await shot(owner,'preview-policy-import')
 await panel.getByRole('button',{name:'Apply reviewed import',exact:true}).click()
 await panel.getByText('Import complete. Historical people have no sign-in or email permissions.',{exact:true}).waitFor()
 await shot(owner,'imported-policy')
 const board=(await json('/api/public/boards')).find(b=>b.name==='Finance history')
 assert.ok(board);assert.equal(board.postingPolicy,'operators');assert.equal(board.showVoteCounts,false);assert.equal(board.showVoters,true);assert.equal(board.anonymousRequesters,true)
 const request=await runtime.db.prepare("SELECT slug FROM requests WHERE title='Schedule monthly finance exports'").first()
 await json(`/api/operator/moderation/${request.slug}`,{verdict:'approved',title:'Schedule monthly finance exports',description:'Make exports available before the monthly review.',boardSlug:board.slug,displayName:'Source customer'},operator)
 const avery=await person('avery@example.test','Avery Morgan'),auth={Authorization:`Bearer ${avery.token}`},customer=await pageFor({token:avery.token}),visitor=await pageFor()
 await visitor.goto(origin+'/?board='+board.slug,{waitUntil:'networkidle'})
 assert.equal(await visitor.getByRole('link',{name:'Submit feedback',exact:true}).count(),0)
 await shot(visitor,'imported-board')
 await customer.goto(origin+`/portal/feedback/${request.slug}`,{waitUntil:'networkidle'})
 const vote=customer.getByRole('button',{name:/^Vote/}).first()
 await vote.click()
 await customer.getByRole('button',{name:/Remove vote/}).waitFor()
 const comment=await json(`/api/public/requests/${request.slug}/comments`,{body:'Keep the original currency in every export.'},auth,'POST',201)
 await json(`/api/operator/comments/${comment.id}/moderate`,{verdict:'approved',publicAuthorDisplayName:'Avery Morgan'},operator)
 await customer.reload({waitUntil:'networkidle'})
 await customer.getByText('Keep the original currency in every export.',{exact:true}).waitFor()
 assert.equal((await customer.locator('main').innerText()).includes('Avery Morgan'),false)
 assert.ok((await customer.locator('main').innerText()).includes('Anonymous'))
 const detail=await json(`/api/public/requests/${request.slug}`)
 assert.equal('voteCount' in detail,false);assert.ok(detail.voters.every(person=>person.displayName==='Anonymous'))
 await shot(customer,'imported-request-anonymous')
 await send('/api/public/requests',{title:'Must be refused',description:'Operators-only board.',boardSlug:board.slug,idempotencyKey:crypto.randomUUID()},auth,'POST',403)
 await json(`/api/operator/boards/${board.slug}`,{commentsAllowed:false},operator,'PATCH')
 await customer.reload({waitUntil:'networkidle'})
 await shot(customer,'imported-comments-disabled')
 await send(`/api/public/requests/${request.slug}/comments`,{body:'Must be refused'},auth,'POST',403)
})
