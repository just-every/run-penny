import assert from 'node:assert/strict'
import {moderationJourney} from './moderation-runtime.mjs'

await moderationJourney('requester-blocking',async({origin,operator,json,send,person,pageFor,capture})=>{
 const eli=await person('eli@example.test','Eli Wong'),noor=await person('noor@example.test','Noor Ahmed')
 const identity={Authorization:`Bearer ${eli.token}`},independent={Authorization:`Bearer ${noor.token}`}
 const own=await json('/api/public/requests',{title:'Schedule monthly finance exports',description:'Finance needs an export before its monthly review.',boardSlug:'finance',idempotencyKey:crypto.randomUUID()},identity,'POST',201)
 await json(`/api/operator/moderation/${own.slug}`,{verdict:'approved',title:'Schedule monthly finance exports',description:'Schedule finance exports each month.',boardSlug:'finance',displayName:'Eli Wong'},operator)
 const shared=await json('/api/operator/requests',{title:'Show invoice currencies',description:'Use the original currency for international invoices.',boardSlug:'finance'},operator,'POST',201)
 await json(`/api/operator/moderation/${shared.slug}`,{verdict:'approved',title:'Show invoice currencies',description:'Use the original currency for international invoices.',boardSlug:'finance',displayName:'Product team'},operator)
 for(const [headers,displayName,body] of [[identity,'Eli Wong','Our finance team uses both USD and EUR.'],[independent,'Noor Ahmed','Please retain the currency code in each CSV row.']]){
  await send(`/api/public/requests/${shared.slug}/vote`,{},headers,'POST',204)
  const comment=await json(`/api/public/requests/${shared.slug}/comments`,{body},headers,'POST',201)
  await json(`/api/operator/comments/${comment.id}/moderate`,{verdict:'approved',publicAuthorDisplayName:displayName},operator)
 }
 const people=await json('/api/operator/requesters?q=eli',undefined,operator),id=people.items.find(person=>person.displayName==='Eli Wong').id
 const owner=await pageFor({cookie:operator.Cookie}),visitor=await pageFor()
 const participating=await pageFor({token:eli.token})
 await participating.goto(origin+`/portal/feedback/${shared.slug}`,{waitUntil:'networkidle'})
 await participating.getByRole('button',{name:'Remove vote',exact:true}).waitFor()
 await owner.goto(origin+'/app/requesters?q=Eli',{waitUntil:'networkidle'})
 const card=owner.locator(`#requesters-${id}`)
 await card.getByText('Active',{exact:true}).waitFor()
 await capture(owner,'requester-active',card)
 await card.getByRole('button',{name:'Block requester',exact:true}).click()
 await card.getByRole('button',{name:'Cancel',exact:true}).click()
 assert.equal(await card.getByRole('button',{name:'Confirm block requester',exact:true}).count(),0)
 await card.getByRole('button',{name:'Block requester',exact:true}).click()
 await capture(owner,'confirm-block',card)
 await card.getByRole('button',{name:'Confirm block requester',exact:true}).click()
 await card.getByText('Blocked',{exact:true}).waitFor()
 await capture(owner,'requester-blocked',card)
 // The requester already has this page open when access is revoked. The real
 // refused mutation must explain the cause and next step without exposing its code.
 await participating.getByRole('button',{name:'Remove vote',exact:true}).click()
 const refusal=participating.getByText(/access is blocked.*contact the workspace owner/i)
 await refusal.waitFor()
 assert.doesNotMatch(await participating.locator('body').innerText(),/requester_blocked|requester blocked/)
 await capture(participating,'requester-action-refused')
 await send(`/api/public/requests/${shared.slug}/vote`,{},identity,'POST',403)
 const missing=await visitor.goto(origin+`/portal/feedback/${own.slug}`,{waitUntil:'networkidle'})
 assert.equal(missing.status(),404)
 await capture(visitor,'blocked-author-hidden')
 await visitor.goto(origin+`/portal/feedback/${shared.slug}`,{waitUntil:'networkidle'})
 await visitor.getByText('Please retain the currency code in each CSV row.',{exact:true}).waitFor()
 assert.equal(await visitor.getByText('Our finance team uses both USD and EUR.',{exact:true}).count(),0)
 assert.equal((await json(`/api/public/requests/${shared.slug}`)).voteCount,1)
 await capture(visitor,'blocked-contributions-hidden')
 await owner.reload({waitUntil:'networkidle'})
 await card.getByRole('button',{name:'Unblock requester',exact:true}).click()
 await card.getByRole('button',{name:'Confirm unblock requester',exact:true}).click()
 await card.getByText('Active',{exact:true}).waitFor()
 await capture(owner,'requester-unblocked',card)
 await visitor.goto(origin+`/portal/feedback/${own.slug}`,{waitUntil:'networkidle'})
 await visitor.getByRole('heading',{name:'Schedule monthly finance exports',exact:true}).waitFor()
 await capture(visitor,'author-restored')
 await visitor.goto(origin+`/portal/feedback/${shared.slug}`,{waitUntil:'networkidle'})
 await visitor.getByText('Our finance team uses both USD and EUR.',{exact:true}).waitFor()
 assert.equal((await json(`/api/public/requests/${shared.slug}`)).voteCount,2)
 await capture(visitor,'contributions-restored')
 await send(`/api/public/requests/${shared.slug}/follow`,{},identity,'POST',204)
 // A session can expire after the confirmation opens. Keep the action refused
 // and tell the operator to sign in again instead of displaying "Action failed".
 await owner.reload({waitUntil:'networkidle'})
 await card.getByRole('button',{name:'Block requester',exact:true}).click()
 await owner.context().clearCookies()
 await card.getByRole('button',{name:'Confirm block requester',exact:true}).click()
 await card.getByRole('alert').filter({hasText:/session.*sign in again/i}).waitFor()
 await capture(owner,'operator-session-ended',card)
 await send(`/api/public/requests/${shared.slug}/vote`,{},identity,'POST',204)
})
