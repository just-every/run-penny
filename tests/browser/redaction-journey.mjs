import assert from 'node:assert/strict'
export async function reviewRedaction({page,runtime,goto,capture}){
 const origin=runtime.origin
 const old=await page.request.post(origin+'/api/operator/evidence',{headers:{Origin:origin},data:{sourceType:'free_text',sourceLabel:'Synthetic prior capture',wording:'Prior captured account ACCOUNT-1234.',observedAt:'2026-10-22T09:00:00Z'}})
 assert.equal(old.status(),201)
 await goto('/app/settings')
 const panel=page.locator('section[aria-labelledby=evidence-redaction]')
 await panel.getByLabel('Enable redaction for new captures',{exact:true}).check()
 await panel.getByLabel('Custom patterns',{exact:true}).fill('ACCOUNT-[0-9]{4}')
 const saved=page.waitForResponse(r=>r.url().endsWith('/api/operator/settings/redaction')&&r.request().method()==='PUT')
 await panel.getByRole('button',{name:'Save redaction rules',exact:true}).click();assert.equal((await saved).status(),200)
 await panel.getByText('Redaction rules saved for new captures.',{exact:true}).waitFor()
 await capture('AI-008-rules-settings')
 await goto('/app/feedback')
 const form=page.getByRole('form',{name:'New evidence',exact:true})
 await form.getByLabel('Source',{exact:true}).selectOption('free_text')
 await form.getByLabel('Source label (required for free text)',{exact:true}).fill('Synthetic support ticket')
 await form.getByLabel('Original wording',{exact:true}).fill('Synthetic Penny ticket: SSN 234-56-7890 and card 4111 1111 1111 1111. ACCOUNT-5678.')
 await form.getByLabel('Observed time',{exact:true}).fill('2026-10-22T09:00')
 const recorded=page.waitForResponse(r=>r.url().endsWith('/api/operator/evidence')&&r.request().method()==='POST')
 await form.getByRole('button',{name:'Record evidence',exact:true}).click();assert.equal((await recorded).status(),201)
 await page.getByText('Synthetic Penny ticket: SSN [REDACTED:ssn] and card [REDACTED:card]. [REDACTED:custom].',{exact:false}).first().waitFor()
 assert.ok(!(await page.locator('body').innerText()).includes('234-56-7890'))
 await capture('AI-008-redacted-item')
 await goto('/app/settings')
 const previewed=page.waitForResponse(r=>r.url().endsWith('/redaction/preview'))
 await panel.getByRole('button',{name:'Preview stored evidence redaction',exact:true}).click()
 const preview=await (await previewed).json();assert.equal(preview.changes,1)
 await panel.getByText('2 evidence versions checked; 1 will change.',{exact:true}).waitFor()
 await capture('AI-008-reapply-counts')
 await panel.getByLabel('I understand this permanently removes the matched wording.',{exact:true}).check()
 const applied=page.waitForResponse(r=>r.url().endsWith('/redaction/reapply'))
 await panel.getByRole('button',{name:'Redact stored evidence permanently',exact:true}).click();assert.equal((await applied).status(),200)
 await panel.getByText('Redaction applied to 1 evidence versions.',{exact:true}).waitFor()
 await goto('/app/feedback')
 await page.getByText('Prior captured account [REDACTED:custom].',{exact:false}).first().waitFor()
 assert.ok(!(await page.locator('body').innerText()).includes('ACCOUNT-1234'))
 await capture('AI-008-reapplied-item')
}
