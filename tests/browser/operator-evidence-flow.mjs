import assert from 'node:assert/strict'

/** One operator takes recorded evidence through linking, authorship and review. */
export async function reviewEvidenceFlow({page,db,capture}) {
 const item=await db.prepare('SELECT * FROM evidence_items WHERE id=(SELECT evidence_id FROM evidence_versions WHERE wording=?)').bind('Browser-local observed time').first()
 const card=page.locator(`#evidence-${item.id}`)
 assert.equal(item.review_state,'unreviewed','[EVID-003] recording starts unreviewed')
 assert.equal(item.source_type,'interview')
 assert.ok(item.recorded_by_operator_id,'[EVID-002] the recording operator is retained')
 assert.equal(item.requester_id,null,'[EVID-002] recording does not infer a requester')
 const open=async()=>{await page.waitForLoadState('networkidle');const summary=card.getByText('Review and link evidence',{exact:true});await summary.waitFor();if(await summary.locator('..').getAttribute('open')===null)await summary.click()}
 await open()
 for(const [title,label,value,target] of [
  ['Link to request','Request','attention-request','request'],
  ['Link to candidate bet','Candidate bet','page-bet-a','bet'],
 ]) {
  await open()
  const form=card.getByRole('form',{name:title,exact:true})
  await form.getByLabel(label,{exact:true}).selectOption(value)
  const saved=page.waitForResponse(r=>new URL(r.url()).pathname===`/api/operator/evidence/${item.id}/links`&&r.request().method()==='PUT')
  await form.getByRole('button',{name:'Save',exact:true}).click()
  assert.equal((await saved).status(),200)
  const links=await (await page.request.get(new URL(`/api/operator/evidence/${item.id}/links`,page.url()).href)).json()
  assert.ok(links.some(link=>link.target===target&&link.targetId===value),'[EVID-003] selected link persists')
  assert.equal(await db.prepare('SELECT review_state FROM evidence_items WHERE id=?').bind(item.id).first('review_state'),'unreviewed','[EVID-003] linking never reviews evidence')
 }
 await open()
 const createRequest=card.getByRole('form',{name:'Create request from evidence',exact:true})
 await createRequest.getByLabel('Request title',{exact:true}).fill('Trace the monthly reporting evidence')
 await createRequest.getByLabel('Request description',{exact:true}).fill('Make the reporting workflow easier to follow.')
 await createRequest.getByLabel('Board',{exact:true}).selectOption('attention-board')
 const created=page.waitForResponse(r=>new URL(r.url()).pathname===`/api/operator/evidence/${item.id}/request`&&r.request().method()==='POST')
 await createRequest.getByRole('button',{name:'Create request',exact:true}).click()
 const response=await created;assert.equal(response.status(),201)
 const request=await response.json()
 const stored=await db.prepare('SELECT * FROM requests WHERE id=?').bind(request.id).first()
 assert.equal(stored.author_operator_id,item.recorded_by_operator_id,'[REQ-029] records operator authorship')
 assert.equal(stored.published_at,null,'[REQ-029] creating from evidence is not publication')
 assert.equal(await db.prepare('SELECT count(*) n FROM request_evidence_links WHERE request_id=? AND evidence_id=?').bind(request.id,item.id).first('n'),1)
 assert.equal((await page.request.get(new URL(`/api/public/requests/${request.slug}`,page.url()).href)).status(),404,'[REQ-029] the unapproved public projection is absent')
 assert.equal(await db.prepare('SELECT count(*) n FROM request_content_submissions WHERE request_id=?').bind(request.id).first('n'),0,'[REQ-029] operator creation has no requester submission hold')
 const approved={verdict:'approved',title:'Reporting workflow request',description:'Follow each reporting step.',boardSlug:'attention-board',displayName:'Owner',categoryId:null}
 const published=await page.request.post(new URL(`/api/operator/moderation/${request.slug}`,page.url()).href,{data:approved,headers:{Origin:new URL(page.url()).origin}})
 assert.equal(published.status(),200,'[REQ-029 REQ-005] publication is a separate explicit action')
 const publicRecord=await (await page.request.get(new URL(`/api/public/requests/${request.slug}`,page.url()).href)).json()
 assert.deepEqual({title:publicRecord.title,description:publicRecord.description,board:publicRecord.board.slug,author:publicRecord.authorDisplayName,category:publicRecord.category,attachments:publicRecord.attachments},{title:approved.title,description:approved.description,board:approved.boardSlug,author:approved.displayName,category:null,attachments:[]})
 assert.doesNotMatch(JSON.stringify(publicRecord),/Browser-local observed time|Trace the monthly reporting evidence|Make the reporting workflow easier to follow/,'[REQ-029] evidence and unapproved working fields stay private')
 const publicPage=await page.context().newPage()
 try {
  await publicPage.goto(new URL(`/portal/feedback/${request.slug}`,page.url()).href)
  await publicPage.getByRole('heading',{name:approved.title,exact:true}).waitFor()
  await capture('operator-request-published',publicPage)
 } finally {await publicPage.close()}
 await open()
 const createDecision=card.getByRole('form',{name:'Create decision from evidence',exact:true})
 await createDecision.getByLabel('Decision question',{exact:true}).fill('Which reporting step should we simplify?')
 await createDecision.getByLabel('Initial bet title',{exact:true}).fill('Explain each reporting step')
 await createDecision.getByLabel('Approach',{exact:true}).fill('Show the next action alongside its evidence.')
 await createDecision.getByLabel('Owner',{exact:true}).selectOption(item.recorded_by_operator_id)
 const decisionCreated=page.waitForResponse(r=>new URL(r.url()).pathname===`/api/operator/evidence/${item.id}/decision`&&r.request().method()==='POST')
 await createDecision.getByRole('button',{name:'Create decision',exact:true}).click()
 const decisionResponse=await decisionCreated;assert.equal(decisionResponse.status(),201)
 const decision=await decisionResponse.json()
 assert.equal(await db.prepare('SELECT count(*) n FROM candidate_bet_evidence_links l JOIN candidate_bets b ON b.id=l.candidate_bet_id WHERE b.decision_id=? AND l.evidence_id=?').bind(decision.id,item.id).first('n'),1,'[EVID-003] a new decision retains its source evidence')
 assert.equal(await db.prepare('SELECT review_state FROM evidence_items WHERE id=?').bind(item.id).first('review_state'),'unreviewed','[EVID-003] creating records never implicitly reviews evidence')
 await open()
 const reviewed=card.getByRole('form',{name:'Mark reviewed',exact:true})
 await reviewed.getByLabel('Review reason',{exact:true}).fill('Linked to the reporting request and decision.')
 await reviewed.getByRole('button',{name:'Save',exact:true}).click()
 await card.getByText('Reviewed',{exact:true}).waitFor()
 assert.deepEqual(await db.prepare('SELECT review_state,review_reason FROM evidence_items WHERE id=?').bind(item.id).first(),{review_state:'reviewed',review_reason:'Linked to the reporting request and decision.'})
 await capture('evidence-reviewed-with-links')
 await open()
 await card.getByRole('form',{name:'Return to unreviewed',exact:true}).getByRole('button',{name:'Save',exact:true}).click()
 await card.getByText('Unreviewed',{exact:true}).waitFor()
 assert.deepEqual(await db.prepare('SELECT review_state,review_reason FROM evidence_items WHERE id=?').bind(item.id).first(),{review_state:'unreviewed',review_reason:null})
 await capture('evidence-returned-to-inbox')
}
