import assert from 'node:assert/strict'
import { moderationJourney } from './moderation-runtime.mjs'

await moderationJourney('rich-changelog',async({runtime,origin,operator,json,person,pageFor,capture})=>{
 const actor=await runtime.db.prepare('SELECT id FROM operators LIMIT 1').first('id')
 const requester=await person('reader@example.test','Release reader'),identity={Authorization:`Bearer ${requester.token}`}
 const request=await json('/api/public/requests',{title:'Monthly reports',description:'Reliable monthly reporting',boardSlug:'finance',idempotencyKey:crypto.randomUUID()},identity,'POST',201)
 await json(`/api/operator/moderation/${request.slug}`,{verdict:'approved',title:'Monthly reports',description:'Prepare monthly reports',boardSlug:'finance',displayName:'Release reader'},operator)
 const requestId=await runtime.db.prepare('SELECT id FROM requests WHERE slug=?').bind(request.slug).first('id')
 const evidence=await json('/api/operator/evidence',{sourceType:'interview',wording:'Finance needs repeatable exports.',observedAt:new Date().toISOString()},operator,'POST',201)
 const decision=await json('/api/operator/decisions',{question:'How should finance prepare monthly reports?',ownerOperatorId:actor},operator,'POST',201)
 const bets=[]
 for(const title of ['Scheduled reports','Manual checklist'])bets.push(await json(`/api/operator/decisions/${decision.id}/bets`,{title,summary:title},operator,'POST',201))
 await json(`/api/operator/evidence/${evidence.id}/links`,{target:'bet',targetId:bets[0].id,stance:'supporting'},operator,'PUT')
 const item=await json(`/api/operator/decisions/${decision.id}/commit`,{selectedCandidateBetId:bets[0].id,rationale:'Repeated exports should be reliable.',ownerOperatorId:actor,confidence:'medium',reviewAt:'2027-04-01'},operator)
 await json(`/api/operator/roadmap/${item.itemId}/approve`,{publicTitle:'Scheduled monthly reports',publicSummary:'Prepare monthly reports consistently.',boardSlug:'finance',requestIds:[requestId]},operator)
 await json(`/api/operator/roadmap/${item.itemId}/move`,{status:'shipped',reason:'Released to customers.',idempotencyKey:crypto.randomUUID()},operator)
 const tag=await json('/api/operator/catalog/tags',{name:'Internal reporting topic'},operator,'POST',201)
 const product=await json('/api/operator/hierarchy/product',{name:'Finance'},operator,'POST',201)
 const component=await json('/api/operator/hierarchy/component',{name:'Reports',parentId:product.id},operator,'POST',201)
 const feature=await json('/api/operator/hierarchy/feature',{name:'Private report engine',parentId:component.id},operator,'POST',201)
 await json(`/api/operator/hierarchy/feature/${feature.id}/link`,{kind:'roadmap',targetId:item.itemId,linked:true},operator,'PUT')
 const owner=await pageFor({cookie:operator.Cookie}),visitor=await pageFor()
 await owner.goto(origin+'/app/releases',{waitUntil:'networkidle'})
 const editor=owner.locator('form').filter({has:owner.getByRole('heading',{name:'Create release draft',exact:true})})
 await editor.getByLabel('New public label',{exact:true}).fill('Automation')
 await Promise.all([owner.waitForResponse(r=>r.url().endsWith('/api/operator/releases/options')),editor.getByRole('button',{name:'Add label',exact:true}).click()])
 await editor.getByLabel('Title',{exact:true}).fill('Faster monthly reporting')
 await editor.getByLabel('Body',{exact:true}).fill('Initial public wording.')
 await editor.getByLabel('Automation',{exact:true}).check()
 await editor.getByLabel('Finance',{exact:true}).check()
 await editor.getByLabel('Internal reporting topic',{exact:true}).check()
 await editor.getByLabel(/Scheduled monthly reports/).check()
 await capture(owner,'create-release-draft')
 const saved=owner.waitForResponse(r=>new URL(r.url()).pathname==='/api/operator/releases'&&r.request().method()==='POST')
 await editor.getByRole('button',{name:'Save draft',exact:true}).click()
 const draft=await(await saved).json()
 await owner.goto(origin+`/app/releases/${draft.slug}`,{waitUntil:'networkidle'})
 const png=Buffer.from(await owner.evaluate(()=>{
  const chart=document.createElement('canvas');chart.width=640;chart.height=300;const ctx=chart.getContext('2d')
  ctx.fillStyle='#fbf9f3';ctx.fillRect(0,0,640,300);ctx.fillStyle='#252623';ctx.font='bold 26px sans-serif';ctx.fillText('Monthly finance reports',32,45)
  ctx.font='16px sans-serif';ctx.fillText('Reporting teams completing exports on time',32,75)
  for(const [index,[month,value]] of [['August',62],['September',74],['October',96]].entries()){
   const x=64+index*180;ctx.fillStyle='#ad4a1f';ctx.fillRect(x,245-value*1.5,100,value*1.5);ctx.fillStyle='#252623';ctx.fillText(month,x,274);ctx.fillText(value+'%',x+28,235-value*1.5)
  }
  return chart.toDataURL('image/png').split(',')[1]
 }),'base64')
 await owner.getByLabel('Image file',{exact:true}).setInputFiles({name:'monthly-chart.png',mimeType:'image/png',buffer:png})
 await Promise.all([owner.waitForResponse(r=>r.url().endsWith('/attachments')&&r.request().method()==='POST'),owner.getByRole('button',{name:'Upload image',exact:true}).click()])
 await owner.getByText('monthly-chart.png',{exact:true}).waitFor()
 await owner.getByText('Recover original image upload',{exact:true}).click()
 const changed=Buffer.from(png);changed[changed.length-1]^=1
 await owner.getByLabel('Original image',{exact:true}).setInputFiles({name:'changed-chart.png',mimeType:'image/png',buffer:changed})
 await Promise.all([owner.waitForResponse(r=>r.url().endsWith('/recover')&&r.status()===409),owner.getByRole('button',{name:'Recover image bytes',exact:true}).click()])
 await capture(owner,'changed-original-refused')
 await owner.getByLabel('Original image',{exact:true}).setInputFiles({name:'monthly-chart.png',mimeType:'image/png',buffer:png})
 await Promise.all([owner.waitForResponse(r=>r.url().endsWith('/recover')&&r.status()===200),owner.getByRole('button',{name:'Recover image bytes',exact:true}).click()])
 await Promise.all([owner.waitForResponse(r=>r.url().endsWith('/approve')&&r.request().method()==='POST'),owner.getByRole('button',{name:'Approve image for public use',exact:true}).click()])
 const markdown=await owner.locator('code').filter({hasText:'monthly-chart.png'}).innerText()
 const imageUrl=markdown.match(/\(([^)]+)\)/)[1]
 assert.equal((await fetch(origin+imageUrl)).status,404)
 await capture(owner,'release-images-before-body')
 const body=`## Ready for finance\n\n**Monthly reports** now run faster.\n\n${markdown}\n\n<script>window.releaseInjected=true</script>\n\n![External tracker](https://tracker.example/pixel.png)\n\n[Video walkthrough](https://www.youtube.com/watch?v=dQw4w9WgXcQ)\n\n[Unapproved host](https://unapproved.example/embed/video)`
 const edit=owner.locator('form').filter({has:owner.getByRole('heading',{name:'Edit release draft',exact:true})})
 await edit.getByLabel('Body',{exact:true}).fill(body)
 await Promise.all([owner.waitForResponse(r=>r.url().endsWith(`/releases/${draft.slug}`)&&r.request().method()==='PATCH'),edit.getByRole('button',{name:'Save draft',exact:true}).click()])
 await capture(owner,'approved-image-draft')
 await Promise.all([owner.waitForResponse(r=>r.url().endsWith('/publish')&&r.request().method()==='POST'),owner.getByRole('button',{name:'Publish release',exact:true}).click()])
 await owner.getByRole('heading',{name:'Customer-safe update',exact:true}).waitFor()
 await capture(owner,'published-release')
 const other=await json('/api/operator/releases',{title:'Small repair',body:'A smaller fix.',releaseType:'fixed',tagIds:[tag.id],publicationDate:new Date().toISOString().slice(0,10),setupUrl:'',targetIds:[item.itemId],productIds:[product.id],authorOperatorId:actor},operator,'POST',201)
 await json(`/api/operator/releases/${other.slug}/publish`,{},operator)
 await visitor.goto(origin+'/portal/updates',{waitUntil:'networkidle'})
 await visitor.getByRole('heading',{name:'Faster monthly reporting',exact:true}).waitFor()
 assert.equal(await visitor.getByRole('img',{name:'monthly-chart.png',exact:true}).evaluate(image=>image.complete&&image.naturalWidth>0),true)
 assert.equal(await visitor.locator('iframe').count(),0)
 assert.equal(await visitor.locator('script').filter({hasText:'releaseInjected'}).count(),0)
 assert.equal(await visitor.evaluate(()=>window.releaseInjected),undefined)
 assert.ok((await visitor.locator('body').innerText()).includes('<script>window.releaseInjected=true</script>'))
 assert.equal((await visitor.locator('body').innerText()).includes('Private report engine'),false)
 assert.equal((await visitor.locator('body').innerText()).includes('Internal reporting topic'),false)
 await capture(visitor,'rich-changelog')
 const customLabel=(await json('/api/operator/releases/labels',undefined,operator)).find(label=>label.name==='Automation')
 await visitor.getByLabel('Filter by label',{exact:true}).selectOption(customLabel.id)
 assert.equal(await visitor.getByRole('heading',{name:'Small repair',exact:true}).count(),0)
 await visitor.getByLabel('Filter by product',{exact:true}).selectOption(product.id)
 await visitor.getByRole('heading',{name:'Faster monthly reporting',exact:true}).waitFor()
 await capture(visitor,'filtered-changelog')
 await visitor.getByLabel('Filter by label',{exact:true}).selectOption('fixed')
 assert.equal(await visitor.getByRole('heading',{name:'Faster monthly reporting',exact:true}).count(),0)
 await visitor.getByRole('heading',{name:'Small repair',exact:true}).waitFor()
 await visitor.goto(origin+`/portal/updates/${draft.slug}`,{waitUntil:'networkidle'})
 await visitor.getByRole('button',{name:'Load video: Video walkthrough',exact:true}).waitFor()
 assert.equal(await visitor.locator('iframe').count(),0)
 await capture(visitor,'rich-release-detail')
 // The paid/network edge stays local while checking the explicit iframe opt-in.
 await visitor.route('https://www.youtube-nocookie.com/**',route=>route.fulfill({contentType:'text/html',body:'<html><body>Video provider fixture</body></html>'}))
 // After explicit opt-in, permit only the approved video origin; the routed
 // provider response is the sole network-edge fixture in this phase.
 visitor.removeAllListeners('request')
 const videoRequests=[]
 visitor.on('request',request=>{if(/^https?:/.test(request.url())&&new URL(request.url()).origin!==origin){assert.equal(new URL(request.url()).origin,'https://www.youtube-nocookie.com');videoRequests.push(request.url())}})
 await visitor.getByRole('button',{name:'Load video: Video walkthrough',exact:true}).click()
 const video=visitor.locator('iframe[title="Video walkthrough"]')
 assert.equal(await video.getAttribute('src'),'https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ')
 await visitor.frameLocator('iframe[title="Video walkthrough"]').getByText('Video provider fixture',{exact:true}).waitFor()
 assert.equal(videoRequests.length,1)
 await capture(visitor,'loaded-approved-video')
})
