-- Learning history and replay fences obey the product maintenance protocol.
-- Restore/erasure writes require the applying lock's durable claim; a phase alone
-- is not authority. Keep original and commitment immutability guards intact.

CREATE TRIGGER data_guard_learning_sources_insert BEFORE INSERT ON learning_sources
WHEN NOT EXISTS(SELECT 1 FROM data_state s WHERE s.singleton=1 AND (s.phase='idle' OR (s.phase='applying' AND EXISTS(SELECT 1 FROM data_apply_claims c WHERE c.operation_id=s.lock_id))))
BEGIN SELECT RAISE(ABORT,'data_maintenance'); END;

