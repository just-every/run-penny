-- Additive archive/erasure maintenance fences. Prior migration bytes are unchanged.
-- Audit provenance also identifies native submissions whose 30-day key was replaced.
UPDATE requests SET slug='feedback-' || lower(id) WHERE id IN
 (SELECT entity_id FROM audit_entries WHERE action='request.submitted' AND entity_type='request');
CREATE TABLE data_state (
 singleton INTEGER PRIMARY KEY CHECK(singleton=1), origin TEXT NOT NULL,
 epoch INTEGER NOT NULL DEFAULT 0, phase TEXT NOT NULL DEFAULT 'idle' CHECK(phase IN ('idle','locked','applying')),
 lock_id TEXT
);
INSERT INTO data_state(singleton,origin) VALUES(1,lower(hex(randomblob(16))));
CREATE TABLE data_tombstones (
 epoch INTEGER NOT NULL, table_name TEXT NOT NULL, key_hash TEXT NOT NULL,
 PRIMARY KEY(table_name,key_hash)
);
CREATE TABLE data_operations (
 id TEXT PRIMARY KEY NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('export','restore','erase')),
 status TEXT NOT NULL CHECK(status IN ('pending','running','pending_r2','running_r2','complete','aborted')),
 payload_json TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL
);
CREATE TABLE data_apply_claims(operation_id TEXT PRIMARY KEY NOT NULL REFERENCES data_operations(id));
