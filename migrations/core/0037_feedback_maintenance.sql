-- Retained move-in product custody obeys the same maintenance admission as
-- the importer tables. Applying alone is not authority: its lock must have a claim.
-- Replace the earlier INSERT-only phase checks; immutable-original guards remain.
DROP TRIGGER feedback_bundle_maintenance;
DROP TRIGGER feedback_original_maintenance;

CREATE TRIGGER penny_feedback_import_bundles_insert BEFORE INSERT ON feedback_import_bundles
WHEN NOT EXISTS(SELECT 1 FROM data_state s WHERE s.singleton=1 AND (s.phase='idle' OR (s.phase='applying' AND EXISTS(SELECT 1 FROM data_apply_claims c WHERE c.operation_id=s.lock_id))))
BEGIN SELECT RAISE(ABORT,'data_maintenance'); END;

